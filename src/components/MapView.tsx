/**
 * Decluttering: below these zooms a city shows its dot only (label on hover/focus/selection).
 * Capitals keep their labels from the start; الزهراء sits 8 km from قرطبة.
 */
const LABEL_MIN_ZOOM_DEFAULT = 6;
const LABEL_MIN_ZOOM: Record<string, number> = { zahra: 8 };

const ATTRIBUTION =
  'خريطة الأساس: <a href="https://www.naturalearthdata.com/" target="_blank" rel="noopener">Natural Earth</a> · ' +
  '<a href="https://earthobservatory.nasa.gov/features/BlueMarble" target="_blank" rel="noopener">NASA Blue Marble</a>';

function escapeHtml(s: string) {
  return s.replace(
    /[&<>"']/g,
    (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]!,
  );
}

export function MapView({ selectedCityId, selectedYear, eventCityId = null, onSelectCity }: MapViewProps) {
  const containerRef = useRef<HTMLDivElement>(null);
  const mapRef = useRef<L.Map | null>(null);
  const markersRef = useRef<Map<string, L.Marker>>(new Map());
  const onSelectRef = useRef(onSelectCity);
  const [tilesError, setTilesError] = useState(false);
  const [mapReady, setMapReady] = useState(false);

  onSelectRef.current = onSelectCity;

  // init map, basemap, labels and markers once
  useEffect(() => {
    const container = containerRef.current;
    if (!container || mapRef.current) return;

    const map = L.map(container, {
      minZoom: 5,
      maxZoom: 9,
      zoomSnap: 0.5,
      zoomDelta: 0.5,
      attributionControl: true,
      zoomControl: true,
      scrollWheelZoom: true,
      maxBounds: MAX_BOUNDS,
      maxBoundsViscosity: 1,
    });
    map.fitBounds(INITIAL_VIEW, { padding: [12, 12], maxZoom: 6.5 });
    map.attributionControl.setPrefix(
      '<a href="https://leafletjs.com" target="_blank" rel="noopener">Leaflet</a>',
    );

    // --- basemap ---
    let failedThisPass = 0;
    const tiles = new LocalTiles("", {
      attribution: ATTRIBUTION,
      minNativeZoom: basemap.minNativeZoom,
      maxNativeZoom: basemap.maxNativeZoom,
      minZoom: 5,
      maxZoom: 9,
      tileSize: basemap.tileSize,
      keepBuffer: 3,
    });
    tiles.on("loading", () => {
      failedThisPass = 0;
    });
    tiles.on("tileerror", () => {
      failedThisPass += 1;
      setTilesError(true);
    });
    tiles.on("load", () => {
      // every visible tile settled; clear the banner if this pass had no failures
      if (failedThisPass === 0) setTilesError(false);
    });
    tiles.addTo(map);

    // --- Arabic geographic labels (non-interactive, shown by zoom) ---
    const labelLayers = GEO_LABELS.map((g) => {
      const html = `<span class="geo-label geo-label--${g.kind}" style="--rot:${g.rotate ?? 0}deg">${escapeHtml(
        g.text,
      )}${g.sub ? `<small>${escapeHtml(g.sub)}</small>` : ""}</span>`;
      const m = L.marker([g.lat, g.lng], {
        icon: L.divIcon({ className: "geo-label-icon", html, iconSize: [0, 0] }),
        interactive: false,
        keyboard: false,
        pane: "overlayPane",
      });
      return { g, m };
    });
    const syncLabels = () => {
      const z = map.getZoom();
      for (const { g, m } of labelLayers) {
        const show = z >= g.minZoom && (g.maxZoom === undefined || z <= g.maxZoom);
        if (show && !map.hasLayer(m)) m.addTo(map);
        if (!show && map.hasLayer(m)) m.remove();
      }
    };
    const syncCityLabels = () => {
      const z = map.getZoom();
      markersRef.current.forEach((marker, id) => {
        const city = getCity(id);
        const min = LABEL_MIN_ZOOM[id] ?? (city?.capital ? 0 : LABEL_MIN_ZOOM_DEFAULT);
        marker.getElement()?.classList.toggle("city-marker--label-hidden", z < min);
      });
    };
    map.on("zoomend", () => {
      syncLabels();
      syncCityLabels();
    });
    syncLabels();

    // --- city markers (created once; selection/period state is applied with classes) ---
    cities.forEach((city) => {
      const icon = L.divIcon({
        className: `city-marker${city.capital ? " city-marker--capital" : ""}`,
        html: `<span class="city-marker__dot" aria-hidden="true"></span><span class="city-marker__label">${escapeHtml(
          city.name,
        )}</span>`,
        iconSize: [16, 16],
        iconAnchor: [8, 8],
        popupAnchor: [0, -10],
      });
      const marker = L.marker([city.lat, city.lng], {
        icon,
        title: city.capital ? `${city.name} (عاصمة)` : city.name,
        alt: city.name,
        riseOnHover: true,
      }).addTo(map);
      marker.bindPopup(
        `<div class="city-popup__body" dir="rtl">
          <strong class="city-popup__name">${escapeHtml(city.name)}</strong>
          ${city.latinName ? `<span class="city-popup__latin" dir="ltr" lang="es">${escapeHtml(city.latinName)}</span>` : ""}
          <p class="city-popup__text">${escapeHtml(city.significance)}</p>
        </div>`,
        { className: "city-popup", offset: [0, -2], maxWidth: 280 },
      );
      marker.on("click", () => onSelectRef.current(city));
      markersRef.current.set(city.id, marker);
    });

    syncCityLabels();
    mapRef.current = map;
    setMapReady(true);

    // Panels around the map change size (grid, drawers) — keep Leaflet's size in sync.
    const ro = typeof ResizeObserver !== "undefined" ? new ResizeObserver(() => map.invalidateSize()) : null;
    ro?.observe(container);

    return () => {
      ro?.disconnect();
      map.remove();
      mapRef.current = null;
      markersRef.current.clear();
    };
  }, []);

  // reflect selection + period on the existing markers
  useEffect(() => {
    if (!mapReady) return;
    const period = selectedYear !== null ? periodAtYear(selectedYear) : undefined;
    markersRef.current.forEach((marker, id) => {
      const city = getCity(id);
      const el = marker.getElement();
      if (!city || !el) return;
      const selected = id === selectedCityId;
      const dim = !!period && !city.periods.includes(period.id);
      el.classList.toggle("city-marker--selected", selected);
      el.classList.toggle("city-marker--event", id === eventCityId && !selected);
      el.classList.toggle("city-marker--dim", dim && !selected);
      el.setAttribute("aria-pressed", String(selected));
      marker.setZIndexOffset(selected ? 1000 : city.capital ? 100 : 0);
    });
  }, [mapReady, selectedCityId, selectedYear, eventCityId]);

  // fly to the selected city (or the selected event's city); close stale popups otherwise
  useEffect(() => {
    const map = mapRef.current;
    if (!map || !mapReady) return;
    const targetId = selectedCityId ?? eventCityId;
    if (!selectedCityId) map.closePopup();
    const city = targetId ? getCity(targetId) : undefined;
    if (!city) return;
    const reduce = window.matchMedia?.("(prefers-reduced-motion: reduce)").matches;
    const zoom = Math.max(map.getZoom(), selectedCityId ? 7 : 6.5);
    if (reduce) map.setView([city.lat, city.lng], zoom);
    else map.flyTo([city.lat, city.lng], zoom, { duration: 0.8 });
    if (!selectedCityId) return;
    const marker = markersRef.current.get(selectedCityId);
    const t = window.setTimeout(() => marker?.openPopup(), reduce ? 0 : 850);
    return () => window.clearTimeout(t);
  }, [selectedCityId, eventCityId, mapReady]);

  const period = selectedYear !== null ? periodAtYear(selectedYear) : undefined;
  const periodName = period ? getPeriod(period.id)?.name : undefined;

  return (
    <div className="map-wrap">
      <div id="map" ref={containerRef} role="region" aria-label="خريطة الأندلس التفاعلية" />
      {tilesError && (
        <div className="map-tiles-error" role="status">
          <Icon name="alert" size={18} />
          <span>
            تعذّر تحميل بعض أجزاء الخريطة الأساسية. علامات المدن ما تزال قابلة للنقر، والتفاصيل في لوحة
            المعلومات.
          </span>
        </div>
      )}
      <div className="map-legend">
        <span className="map-legend__item">
          <span className="map-legend__swatch map-legend__swatch--capital" aria-hidden="true" /> عاصمة
        </span>
        <span className="map-legend__item">
          <span className="map-legend__swatch" aria-hidden="true" /> مدينة
        </span>
        {periodName && (
          <span className="map-legend__item">
            <span className="map-legend__swatch map-legend__swatch--dim" aria-hidden="true" /> خارج «{periodName}»
          </span>
        )}
      </div>
    </div>
  );
}
